-- Зачем: на экранах крутится не только коммерческая реклама, но и материалы
-- ведомств (социальная реклама, объявления). Владелец у них такой же —
-- со своими папками и роликами, — но денег с него не берут: тарифа нет,
-- счета не выставляются, в дебиторку он не попадает.
--
-- Отдельную таблицу не заводим намеренно: ролики, папки, модерация 38-ФЗ,
-- расписание и отчёты у них устроены точно так же, и дублировать всю эту
-- механику ради одного признака было бы дороже в поддержке.
-- ============================================================

ALTER TABLE advertisers
    ADD COLUMN IF NOT EXISTS kind VARCHAR(16) NOT NULL DEFAULT 'advertiser';

-- Ограничение добавляем отдельно: ADD CONSTRAINT IF NOT EXISTS в Postgres нет.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'advertisers_kind_check') THEN
        ALTER TABLE advertisers
            ADD CONSTRAINT advertisers_kind_check CHECK (kind IN ('advertiser', 'gov'));
    END IF;
END $$;

-- Служебная запись («Заглушки» и прочее внутреннее) — не коммерческий
-- рекламодатель, счетов по ней быть не должно.
UPDATE advertisers SET kind = 'gov' WHERE name = 'Служебное' AND kind = 'advertiser';

