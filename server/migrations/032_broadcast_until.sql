-- ============================================================
-- Digital Signage — Вариант Б (Мини ПК)
-- Миграция 032: срок общего эфира («Эфир сети»)
-- ------------------------------------------------------------
-- Идемпотентна. Применяется ПОСЛЕ 031_placements.sql.
--
-- until_at — до какого момента идёт общий эфир: наивное МСК (как все
-- отметки времени показов), пишется из Python, не NOW() Postgres
-- (контейнер БД живёт в UTC). NULL = «до отмены» — эфир идёт, пока
-- его не выключат вручную. Когда момент наступает, эфир считается
-- выключенным сразу (broadcast_rules.effective_on), а Celery-задача
-- expire_broadcast раз в минуту приводит строку в порядок и пишет
-- в журнал «Общий эфир завершён по времени».
-- ============================================================

ALTER TABLE network_broadcast ADD COLUMN IF NOT EXISTS until_at TIMESTAMP;
