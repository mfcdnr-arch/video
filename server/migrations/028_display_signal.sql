-- ============================================================
-- Digital Signage — Вариант Б (Мини ПК)
-- Миграция 028: контроль подключения видеовыхода (HDMI/DisplayPort)
-- ------------------------------------------------------------
-- Идемпотентна. Применяется ПОСЛЕ 027_screen_diagnostics.sql.
--
-- Зачем: экран мог числиться «онлайн, играет», а монитор при этом был
-- отключён или выключен — узнавали об этом только со слов людей на месте.
-- Агент читает /sys/class/drm/*/status (ядро сообщает, есть ли на выходе
-- подключённый приёмник) и шлёт результат в heartbeat.
--
-- ВАЖНО про границы метода: это детект КАБЕЛЯ/EDID, а не «картинка видна».
-- Монитор, выключенный кнопкой, часто продолжает отвечать по DDC и
-- остаётся `connected`. Значение NULL = агент старой версии или ядро
-- не отдаёт статус (нет /sys/class/drm) — тревогу по NULL НЕ поднимаем.
-- ============================================================

ALTER TABLE screens
    ADD COLUMN IF NOT EXISTS display_connected  BOOLEAN,        -- NULL = неизвестно
    ADD COLUMN IF NOT EXISTS display_outputs    VARCHAR(200),   -- 'HDMI-A-1:connected, DP-1:disconnected'
    ADD COLUMN IF NOT EXISTS display_changed_at TIMESTAMP;      -- когда состояние поменялось

-- История: тот же признак в понедельных снимках состояния мини-ПК.
ALTER TABLE minipc_status
    ADD COLUMN IF NOT EXISTS display_connected BOOLEAN;

-- Отдельный выключатель уведомления (рядом с офлайн/диском/битым роликом).
ALTER TABLE notification_settings
    ADD COLUMN IF NOT EXISTS notify_display BOOLEAN NOT NULL DEFAULT TRUE;

