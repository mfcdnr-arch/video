#!/bin/bash
# ui_test.sh — браузерный (E2E) прогон админ-панели ПЕРЕД релизом.
#
# Дополняет smoke_test.sh: тот проверяет HTTP-эндпоинты, а этот — сам
# интерфейс. Кнопка может звать неверный метод или падать в JS, при том что
# API зелёный: именно так выглядели почти все дефекты панели, найденные на
# пилоте живым кликом.
#
# Что проверяет: вход, открытие всех разделов меню, нажатие всех «безопасных»
# кнопок каждого раздела (разрушающие не трогаются), цикл «создать → увидеть →
# удалить» для экрана, просмотр ролика, ПЛЕЙЛИСТ целиком (окно с поиском и
# повторами ×N, шаг «Куда и когда», карточка «Где и когда идёт», Расписание
# «По датам», отмена показа и удаление), «Эфир сети» (правило «в сети»,
# таблица, поиск, панель «О плейлисте», правка поверх страницы, полоса общего
# эфира и окно включения), «Бегущую строку» (шаблон, запуск на свой экран, подтверждение
# экрана, «Стоп», правка, снятие), индикатор монитора, «Скачать» бэкапа и архива
# диагностики (с входом качается, без входа и по токену экрана — 401), файлы
# медиатеки (без входа — 401; по cookie входа — кадр просмотра, миниатюра,
# «Скачать», Range; экран по X-Token качает одобренный ролик), «Копию на флешку»
# (напоминание на дашборде и блок в «Настройках»; с E2E_ALLOW_OFFSITE=1 — ещё и
# окна пароля и скачивания, сами файлы копии и роликов, зелёное напоминание).
# Любая ошибка в консоли браузера или ответ HTTP ≥400 — провал прогона.
#
# Для плейлиста прогон сам заводит тестовый экран и ролик «E2E_…» и убирает их
# в конце (даже при провале), так что на пустом стенде он тоже проходит.
# Запускать на стенде или стеке без живых экранов. Тестовый показ и бегущая строка
# уходят только на собственный экран прогона E2E_стенд_*, настоящие экраны их не
# получают; но при жёстком обрыве прогона его объекты остаются в панели (удалить
# плейлист E2E_плейлист_*, ролик E2E_ролик_*, экран E2E_стенд_*, бегущую строку и
# шаблон «E2E_строка_*»; см. docs/Техдокументация/04_ТЕСТЫ.md §3).
#
# Использование:   bash ui_test.sh
# Переменные:      ADMIN_USER (по умолч. admin), ADMIN_PASS (admin123),
#                  DS_URL (по умолч. http://nginx — адрес панели ИЗНУТРИ
#                  docker-сети стека),
#                  E2E_ALLOW_BROADCAST=1 — шаги «Общий эфир» (включает эфир на ВСЕ
#                  экраны сети до следующего часа и выключает, прежнее состояние
#                  возвращается) и бегущая строка «на все экраны» (15 минут, потом
#                  снимается), поэтому только на стенде; без переменной шаги
#                  пропускаются с пометкой,
#                  E2E_ALLOW_OFFSITE=1 — шаги «Копия на флешку»: до прогона и после него
#                  скрипт СБРАСЫВАЕТ пароль на копию на сервере (docker exec ds_api python
#                  /app/reset_offsite_password.py), прогон задаёт тестовый пароль
#                  E2E-copy-pass-1, собирает и скачивает копию и ролики (двигает отметку
#                  «последняя копия» и «водяной знак» роликов) — только на стенде: скрипт
#                  до любых действий проверяет, что ds_api из compose-проекта dsdev, иначе
#                  отказ с кодом 1; без переменной шаги пропускаются с пометкой,
#                  E2E_SHOTS_DIR=папка — сохранить туда снимки экрана шага «Копия на
#                  флешку» (нужен E2E_ALLOW_OFFSITE=1; папка монтируется в контейнер).
#
# Chromium не ставится на сервер: прогон идёт в одноразовом контейнере
# официального образа puppeteer, подключённом к сети стека. Первый запуск
# скачивает образ (~1 ГБ), дальше он берётся из кеша.
#
# Код возврата 0 — всё чисто; 1 — есть провалы (подробности в выводе).
set -uo pipefail
cd "$(dirname "$0")"

ADMIN_USER="${ADMIN_USER:-admin}"
ADMIN_PASS="${ADMIN_PASS:-admin123}"
DS_URL="${DS_URL:-http://nginx}"
IMAGE="${UI_TEST_IMAGE:-ghcr.io/puppeteer/puppeteer:23.11.1}"

command -v docker >/dev/null 2>&1 || { echo "ОШИБКА: docker не найден."; exit 1; }

# Сеть стека (имя зависит от каталога проекта — определяем по контейнеру nginx).
NET=$(docker inspect -f '{{range $k,$v := .NetworkSettings.Networks}}{{$k}}{{end}}' ds_nginx 2>/dev/null)
if [ -z "$NET" ]; then
    echo "ОШИБКА: контейнер ds_nginx не запущен — панель проверять негде."
    echo "      └─ Поднимите стек: docker compose up -d  (или bash install_server.sh)"
    exit 1
fi

# «Копия на флешку» (E2E_ALLOW_OFFSITE=1): пароль на копию сбрасывается на сервере ДО прогона (прогон
# задаёт его сам и ждёт, что его нет) и ПОСЛЕ — в том числе при Ctrl+C и при обрыве: стенд остаётся без пароля.
# Охрана: шаг стирает пароль на копию и сдвигает «водяной знак» роликов (сброс пароля его не откатывает), а имя
# контейнера ds_api у боевого сервера такое же, как у стенда. Поэтому ПЕРВЫМ делом, до trap и любого сброса,
# проверяем метку compose-проекта ds_api: только dsdev (bash dev_stand.sh up), иначе отказ и провал прогона.
OFFSITE_RESET="docker exec ds_api python /app/reset_offsite_password.py"
E2E_DECRYPT_CMD=""
if [ "${E2E_ALLOW_OFFSITE:-}" = "1" ]; then
    if [ "$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' ds_api 2>/dev/null)" != "dsdev" ]; then
        echo "ОШИБКА: шаг копии на флешку с флагом — только на стенде dsdev (bash dev_stand.sh up); пропущено."
        echo "      └─ Контейнер ds_api не из compose-проекта dsdev: это может быть боевой сервер, ничего не тронуто."
        exit 1
    fi
    # команда расшифровки — как её знает сервер: в инструкции на флешке она должна стоять слово в слово
    E2E_DECRYPT_CMD=$(docker exec ds_api python -c "import sys; sys.path.insert(0, '/app'); from offsite_crypto import OPENSSL_DECRYPT_CMD; print(OPENSSL_DECRYPT_CMD)" 2>/dev/null)
    if [ -z "$E2E_DECRYPT_CMD" ]; then
        echo "ОШИБКА: не удалось прочитать команду расшифровки с сервера (docker exec ds_api python -c ... OPENSSL_DECRYPT_CMD)."
        exit 1
    fi
    trap 'if $OFFSITE_RESET >/dev/null 2>&1; then echo "• Пароль на копию сброшен (стенд без пароля)."; else echo "ПРЕДУПРЕЖДЕНИЕ: пароль на копию не сбросился — выполните: $OFFSITE_RESET"; fi' EXIT
    if ! $OFFSITE_RESET >/dev/null 2>&1; then
        echo "ОШИБКА: не удалось сбросить пароль на копию ($OFFSITE_RESET)."
        echo "      └─ Без сброса шаги «Копия на флешку» не начать с чистого листа."
        exit 1
    fi
fi

# Снимки экрана шага «Копия на флешку»: папка хоста монтируется в контейнер как /shots
SHOTS_ARGS=()
if [ -n "${E2E_SHOTS_DIR:-}" ]; then
    mkdir -p "$E2E_SHOTS_DIR" && chmod 777 "$E2E_SHOTS_DIR"
    SHOTS_ARGS=(-v "$E2E_SHOTS_DIR":/shots -e E2E_SHOTS_DIR=/shots)
fi

echo "• Прогон панели ($DS_URL, сеть $NET, образ $IMAGE)…"
docker run --rm --network "$NET" \
    -v "$PWD/ui_tests":/ui:ro \
    -e DS_URL="$DS_URL" -e ADMIN_USER="$ADMIN_USER" -e ADMIN_PASS="$ADMIN_PASS" \
    -e E2E_ALLOW_BROADCAST="${E2E_ALLOW_BROADCAST:-}" \
    -e E2E_ALLOW_OFFSITE="${E2E_ALLOW_OFFSITE:-}" \
    -e E2E_DECRYPT_CMD="$E2E_DECRYPT_CMD" \
    "${SHOTS_ARGS[@]+"${SHOTS_ARGS[@]}"}" \
    -e NODE_PATH=/home/pptruser/node_modules \
    --entrypoint node "$IMAGE" /ui/ui_test.js
RC=$?

if [ "$RC" -ne 0 ]; then
    echo
    echo "Прогон нашёл проблемы. Как читать вывод:"
    echo "  ✗ строка раздела   — вью не открылось или отдало ошибку;"
    echo "  ✗ строка кнопки    — клик привёл к ошибке в консоли/HTTP ≥400;"
    echo "  блок «Ошибки консоли / HTTP» — где именно (шаг → сообщение)."
fi
exit "$RC"
